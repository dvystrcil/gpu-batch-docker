#!/usr/bin/env bash
set -euo pipefail

# Smoke test for prusaslicer CLI in gpu-batch-prusaslicer.
# Runs the real entrypoint against a fake moonraker, so it proves the
# composition a Job runs: guard -> PrusaSlicer step -> output check.
# Two cases:
#   1. printer "idle": the job must run and produce valid gcode
#   2. printer "printing": the job must be refused and produce no output
# Prints SMOKE-COMPLETE only as its last line.

set +e
IMG=${1:-prusaslicer-test}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
chmod 777 "$WORK"

# Create a minimal valid STL file for testing
cat > "$WORK/test_part.stl" <<'STL'
solid test
  facet normal 0 0 1
    vertex 0 0 0
    vertex 1 0 0
    vertex 0 1 0
  endfacet
endsolid test
STL

cat > "$WORK/spec.json" <<'JSON'
{"id": "prusaslicer-smoke", "steps": [
  {"name": "export-gcode", "timeout_s": 300,
   "argv": ["sh", "-c", "xvfb-run -a flatpak run --filesystem=/work:rw com.prusa3d.PrusaSlicer --export-gcode /work/test_part.stl -o /workdir/test_part.gcode"]}],
 "expect_outputs": ["test_part.gcode"], "min_outputs": 1, "notify": null}
JSON

fake_moonraker() {  # $1 = state; serves print_stats on 127.0.0.1:7125
  cat <<PY
import json, http.server
class H(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def do_GET(self):
        self.send_response(200); self.end_headers()
        self.wfile.write(json.dumps({"result": {"status": {"print_stats": {"state": "$1"}}}}).encode())
http.server.HTTPServer(("127.0.0.1", 7125), H).serve_forever()
PY
}

run_case() {  # $1 = case dir, $2 = printer state
  mkdir -p "$WORK/$1"
  fake_moonraker "$2" > "$WORK/$1/fake.py"
  docker create --name "gpu-batch-smoke-prusaslicer-$1-$$" \
    --add-host=host.docker.internal:host-gateway \
    -e MOONRAKER_URL=http://host.docker.internal:7125 \
    -e GPU_BATCH_NOTIFY_URL= \
    --entrypoint sh "$IMG" -c \
    "python3 /work/$1/fake.py 2>&1 & python3 /usr/local/bin/wait-for-port.py 7125 10; python3 -m gpu_batch.runner /work/spec.json" >/dev/null
  docker cp "$WORK/." "gpu-batch-smoke-prusaslicer-$1-$$:/work"
  docker start -a "gpu-batch-smoke-prusaslicer-$1-$$"
  rc=$?
  docker cp "gpu-batch-smoke-prusaslicer-$1-$$:/work/." "$WORK/$1/"
  docker rm -f "gpu-batch-smoke-prusaslicer-$1-$$" >/dev/null
  echo "$1: exit $rc"
  return 0
}

state() { python3 -c 'import json,sys; s=json.load(open(sys.argv[1])); print(s["state"])' "$1"; }
field() { python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))[sys.argv[2]])' "$1" "$2"; }

run_case idle standby
[ "$(state "$WORK/idle/status.json")" = succeeded ] || { echo "FAIL: idle job did not succeed"; exit 1; }
[ -s "$WORK/idle/vt350.gcode" ] || { echo "FAIL: vt350.gcode not produced"; exit 1; }
grep -q "Generated by PrusaSlicer" "$WORK/idle/vt350.gcode" || { echo "FAIL: gcode missing PrusaSlicer marker"; exit 1; }

run_case busy printing
[ "$(state "$WORK/busy/status.json")" = refused ] || { echo "FAIL: job was not refused while printing"; exit 1; }
[ ! -e "$WORK/busy/vt350.gcode" ] || { echo "FAIL: a refused job produced output"; exit 1; }

echo "SMOKE-COMPLETE"
