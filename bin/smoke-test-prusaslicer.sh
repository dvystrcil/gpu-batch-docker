#!/usr/bin/env bash
# Smoke-test a built gpu-batch-prusaslicer image (homelab#1961 AC4).
#
# Runs the image's real entrypoint against a fake moonraker, so it proves the
# composition a Job runs: guard -> PrusaSlicer step -> output check ->
# status.json. Three cases:
#   1. printer "standby": slice a 20 mm cube; a check step asserts the G-code
#      (PrusaSlicer's own header with the pinned version, layers, extrusion,
#      the footer's time + filament) and only then moves it to out/
#   2. printer "printing", guard on: refused, no step ran
#   3. printer "printing", GPU_BATCH_PRINT_GUARD=off (what the CPU-only
#      template sets, gpu-batch-docker#9): the slice runs, because this
#      container has no GPU
# HOME points at a path that does not exist: a pod's HOME is not writable,
# so the slicer must get everything it writes from --datadir.
# Prints SMOKE-COMPLETE only as its last line (ci-assert-completion-marker).
#
#   bin/smoke-test-prusaslicer.sh <image>
set -euo pipefail
IMG=${1:?usage: smoke-test-prusaslicer.sh <image>}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
chmod 777 "$WORK"

# A closed 20 mm cube, ASCII STL, 12 facets.
python3 - "$WORK/cube.stl" <<'PY'
import sys
s = 20.0
v = [(x, y, z) for x in (0, s) for y in (0, s) for z in (0, s)]
quads = [(0, 2, 6, 4, (0, 0, -1)), (1, 5, 7, 3, (0, 0, 1)), (0, 4, 5, 1, (0, -1, 0)),
         (2, 3, 7, 6, (0, 1, 0)), (0, 1, 3, 2, (-1, 0, 0)), (4, 6, 7, 5, (1, 0, 0))]
out = ["solid cube"]
for a, b, c, d, n in quads:
    for tri in ((a, b, c), (a, c, d)):
        out.append("  facet normal %g %g %g" % n)
        out.append("    outer loop")
        out += ["      vertex %g %g %g" % v[i] for i in tri]
        out += ["    endloop", "  endfacet"]
out.append("endsolid cube")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
PY

# The slicer's exit code is not the proof: this step reads the G-code and
# moves it to out/ only if every check passes.
cat > "$WORK/check_gcode.py" <<'PY'
import json, os, re, sys
src, out, want = sys.argv[1], sys.argv[2], sys.argv[3]
g = open(src).read()
head = g.splitlines()[0] if g else ""
m = re.match(r"; generated by PrusaSlicer (\S+) on ", head)
assert m, f"no PrusaSlicer header: {head!r}"
assert m.group(1) == want, f"version {m.group(1)}, want {want}"
layers = g.count(";LAYER_CHANGE")
assert layers >= 50, f"{layers} layers for a 20 mm cube"
assert re.search(r"^G1 X[\d.]+ Y[\d.]+ E[\d.]+", g, re.M), "no extrusion moves"
fil = re.search(r"^; filament used \[mm\] = ([\d.]+)", g, re.M)
t = re.search(r"^; estimated printing time \(normal mode\) = (.+)$", g, re.M)
assert fil and float(fil.group(1)) > 100 and t, "no footer (filament, time)"
os.makedirs(out, exist_ok=True)
os.replace(src, os.path.join(out, "cube.gcode"))
json.dump({"version": m.group(1), "layers": layers, "filament_mm": float(fil.group(1)),
           "time": t.group(1)}, open(os.path.join(out, "gcode.json"), "w"))
PY

fake_moonraker() {  # $1 = state; serves print_stats on 127.0.0.1:7125
  cat <<PY
import json, http.server
class H(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def do_GET(self):
        self.send_response(200); self.end_headers()
        self.wfile.write(json.dumps({"result": {"status": {"print_stats": {"state": "$1"}}}}).encode())
http.server.HTTPServer(("127.0.0.1", 7125), H).serve_forever()
PY
}

run_case() {  # $1 = case dir, $2 = printer state, $3 = GPU_BATCH_PRINT_GUARD value
  mkdir -p "$WORK/$1" && chmod 777 "$WORK/$1"
  cat > "$WORK/$1/spec.json" <<JSON
{"id": "$1", "steps": [
  {"name": "slice", "timeout_s": 300,
   "argv": ["sh", "-c", "mkdir -p {job}/tmp/datadir && exec prusa-slicer --datadir {job}/tmp/datadir --export-gcode --center 100,100 --output {job}/tmp/cube.gcode /work/cube.stl"]},
  {"name": "check", "timeout_s": 60,
   "argv": ["python3", "/work/check_gcode.py", "{job}/tmp/cube.gcode", "{job}/out", "${EXPECT_PRUSASLICER:-2.9.7}"]}],
 "expect_outputs": ["out/cube.gcode", "out/gcode.json"], "min_outputs": 2, "notify": null}
JSON
  fake_moonraker "$2" > "$WORK/$1/fake.py"
  # docker cp, not -v: on the ARC runners docker is a DinD sidecar, so a
  # bind mount names a path on the DAEMON's filesystem (see smoke-test.sh).
  local ctr="gpu-batch-smoke-prusaslicer-$1-$$"
  docker create --name "$ctr" -e MOONRAKER_URL=http://127.0.0.1:7125 -e HOME=/nonexistent \
    -e GPU_BATCH_PRINT_GUARD="$3" \
    --entrypoint sh "$IMG" -c \
    "python3 /work/$1/fake.py & sleep 1; python3 -m gpu_batch.runner /work/$1/spec.json" >/dev/null
  docker cp "$WORK/." "$ctr:/work"
  set +e
  docker start -a "$ctr"
  rc=$?
  set -e
  docker cp "$ctr:/work/$1/." "$WORK/$1/"
  docker rm -f "$ctr" >/dev/null
  echo "$1: exit $rc"
  return 0
}

state() { python3 -c 'import json,sys; s=json.load(open(sys.argv[1])); print(s["state"]); print(s["reason"], file=sys.stderr)' "$1"; }
field() { python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))[sys.argv[2]])' "$1" "$2"; }

run_case idle standby ""
[ "$(state "$WORK/idle/status.json")" = succeeded ] || { cat "$WORK/idle/job.log" "$WORK/idle/job.err" || true; echo "FAIL: idle job did not succeed"; exit 1; }
[ -s "$WORK/idle/out/cube.gcode" ] || { echo "FAIL: cube.gcode missing or empty"; exit 1; }
echo "gcode: $(cat "$WORK/idle/out/gcode.json")"

run_case busy printing ""
[ "$(state "$WORK/busy/status.json")" = refused ] || { echo "FAIL: job was not refused while printing"; exit 1; }
[ ! -e "$WORK/busy/out" ] && [ ! -e "$WORK/busy/tmp" ] || { echo "FAIL: a refused job ran a step"; exit 1; }

run_case cpu printing off
[ "$(state "$WORK/cpu/status.json")" = succeeded ] || { cat "$WORK/cpu/job.err" || true; echo "FAIL: CPU-only job (guard off, no GPU) did not run"; exit 1; }
grep -q 'CPU-only' "$WORK/cpu/status.json" || { echo "FAIL: guard-off reason not recorded"; exit 1; }
[ -s "$WORK/cpu/out/cube.gcode" ] || { echo "FAIL: CPU-only job produced no G-code"; exit 1; }

echo "SMOKE-COMPLETE"
