"""The harness's cases and its assert step (gpu-batch-docker#10).

  python3 check.py <case>          assert: read every tool's status.json, its
                                   outputs, the notify-sink files and the mock's
                                   request log. Last line COMPOSE-TEST-OK only if
                                   every check passed; exit 1 otherwise.
  python3 check.py --env <case>    KEY=VALUE lines for the driver (mock state,
                                   blender env)
  python3 check.py --print-starter <case>
                                   print-starts only: once blender's step is
                                   running, switch the mock to "printing"
"""
import json
import os
import re
import struct
import sys
import time
import urllib.request
from pathlib import Path

WORK = Path(os.environ.get("WORK", "/work"))
MOCK = os.environ.get("MOCK_URL", "http://moonraker-mock:7125")
TOOLS = ("freecad", "prusaslicer", "blender")
CPU_ONLY = "print guard off: CPU-only job, no GPU in this container"
# The pinned tool versions (Dockerfile ARGs); a bump changes these too.
EXPECT_FREECAD = os.environ.get("EXPECT_FREECAD", "26.3.0")
EXPECT_PRUSASLICER = os.environ.get("EXPECT_PRUSASLICER", "2.9.7")

# Per case: the mock's starting state, blender's extra env, what each tool
# must end as, what blender's reason must contain, and the guard probes the
# mock must have seen. freecad and prusaslicer run with the guard off (no
# GPU) in every case, so they never probe: the probe count is blender's alone.
CASES = {
    "chain": {
        "mock": "standby", "blender_env": {},
        "blender": ("succeeded", ["standby"]), "probes": ["standby"]},
    "printing": {
        "mock": "printing", "blender_env": {},
        "blender": ("refused", ["Neptune is printing"]), "probes": ["printing"]},
    "print-starts": {
        "mock": "standby", "blender_env": {},
        "blender": ("aborted", ["stopped", "printing"]), "probes": ["standby", "printing"]},
    "unreachable": {
        "mock": "unreachable", "blender_env": {},
        "blender": ("refused", ["unreachable", "Obico"]), "probes": ["unreachable"]},
    "guard-ignored": {
        "mock": "printing",
        "blender_env": {"GPU_BATCH_PRINT_GUARD": "off", "NVIDIA_VISIBLE_DEVICES": "GPU-test"},
        "blender": ("refused", ["GPU_BATCH_PRINT_GUARD=off ignored", "printing"]), "probes": ["printing"]},
}


class Checker:
    def __init__(self):
        self.failed = 0

    def ok(self, cond, what, detail=""):
        print(("PASS " if cond else "FAIL ") + what + ("" if cond or not detail else f": {detail}"), flush=True)
        if not cond:
            self.failed += 1
        return cond


def _json(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def stl_triangles(data: bytes) -> int:
    if data.startswith(b"solid") and b"facet normal" in data:
        return data.count(b"facet normal")
    if len(data) >= 84:
        n = struct.unpack("<I", data[80:84])[0]
        if len(data) == 84 + 50 * n:
            return n
    return 0


def png_size(data: bytes):
    if data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", data[16:24])


def check_output(c: Checker, tool: str):
    d = WORK / tool / "out"
    if tool == "freecad":
        data = (d / "part.stl").read_bytes() if (d / "part.stl").exists() else b""
        n = stl_triangles(data)
        c.ok(n >= 12, "freecad: out/part.stl is a closed-box STL", f"{n} triangles")
        h = _json(d / "headless.json") or {}
        c.ok(h.get("freecad") == EXPECT_FREECAD, f"freecad: version {EXPECT_FREECAD}", str(h.get("freecad")))
        c.ok(h.get("gui_up") is False, "freecad: freecadcmd runs without a GUI", str(h.get("gui_up")))
        c.ok("/Mod/fasteners/" in str(h.get("fasteners")) and (h.get("screw_volume_mm3") or 0) > 10,
             "freecad: Fasteners (from the image's Mod dir) generated an M3x8 screw", str(h))
        g = _json(d / "gui.json") or {}
        c.ok(g.get("gui_up") is True and g.get("main_window") is True,
             "freecad: GUI mode comes up under xvfb-run", str(g))
    elif tool == "prusaslicer":
        g = (d / "part.gcode").read_text(errors="replace") if (d / "part.gcode").exists() else ""
        head = g.splitlines()[0] if g else ""
        m = re.match(r"; generated by PrusaSlicer (\S+) on ", head)
        c.ok(m is not None and m.group(1) == EXPECT_PRUSASLICER,
             f"prusaslicer: G-code header says PrusaSlicer {EXPECT_PRUSASLICER}", repr(head))
        fil = re.search(r"^; filament used \[mm\] = ([\d.]+)", g, re.M)
        c.ok(fil is not None and float(fil.group(1)) > 100
             and re.search(r"^; estimated printing time \(normal mode\) = ", g, re.M) is not None,
             "prusaslicer: G-code footer has filament and time", fil.group(0) if fil else "no footer")
        zs = [float(z) for z in re.findall(r"^;Z:([\d.]+)", g, re.M)]
        top = max(zs, default=0.0)
        c.ok(len(zs) >= 20 and 9.7 <= top <= 10.3, "prusaslicer: G-code layers reach the box's 10 mm",
             f"{len(zs)} layers, top Z {top}")
        c.ok(re.search(r"^G1 X[\d.]+ Y[\d.]+ E[\d.]+", g, re.M) is not None, "prusaslicer: G-code extrudes")
    elif tool == "blender":
        data = (d / "part.png").read_bytes() if (d / "part.png").exists() else b""
        c.ok(png_size(data) == (64, 64), "blender: out/part.png is a 64x64 PNG", str(png_size(data)))


def check_tool(c: Checker, tool: str, want_state: str, want_reason: list[str]):
    st = _json(WORK / tool / "status.json")
    if not c.ok(st is not None, f"{tool}: status.json exists and parses"):
        return
    c.ok(st.get("state") == want_state, f"{tool}: state {want_state}",
         f"got {st.get('state')!r}: {st.get('reason')!r}")
    text = f"{st.get('reason', '')} | {st.get('guard', '')}"
    for frag in want_reason:
        c.ok(frag in text, f"{tool}: reason/guard mentions {frag!r}", text)
    c.ok(st.get("notified") is True, f"{tool}: runner reports the webhook delivered",
         st.get("notify_error", ""))
    sent = _json(WORK / "_notify" / f"{tool}.json")
    c.ok(sent is not None and all(sent.get(k) == st.get(k) for k in ("id", "state", "reason", "outputs")),
         f"{tool}: notify-sink got the same status body")
    cnt = (WORK / "_notify" / f"{tool}.count")
    c.ok(cnt.exists() and cnt.read_text() == "1", f"{tool}: webhook fired exactly once",
         cnt.read_text() if cnt.exists() else "never")
    if want_state == "succeeded":
        check_output(c, tool)
    elif want_state == "refused":
        c.ok(st.get("steps") == [] and not (WORK / tool / "out").exists(), f"{tool}: refused job ran no step")


def run_assert(case: str) -> int:
    c = Checker()
    spec = CASES[case]
    c.ok((WORK / "_case").read_text() == case if (WORK / "_case").exists() else False,
         f"work volume was seeded for {case}")
    for tool in ("freecad", "prusaslicer"):
        check_tool(c, tool, "succeeded", [CPU_ONLY])
    check_tool(c, "blender", *spec["blender"])
    try:
        log = json.loads(urllib.request.urlopen(MOCK + "/_mock/requests", timeout=10).read())
    except Exception as e:  # noqa: BLE001
        log = None
        c.ok(False, "moonraker-mock request log readable", f"{type(e).__name__}: {e}")
    if log is not None:
        served = [e["served"] for e in log]
        want = spec["probes"]
        if case == "print-starts":
            # one probe at start, then the 60 s re-checks until one sees the print
            good = len(served) >= 2 and served[0] == "standby" and served[-1] == "printing"
        else:
            good = served == want
        c.ok(good, f"moonraker-mock saw blender's probes only ({want})", f"served {served}")
    for tool in TOOLS:
        st = _json(WORK / tool / "status.json") or {}
        steps = st.get("steps") or [{}]
        print(f"  {tool}: {st.get('state')} started {steps[0].get('started')} finished {steps[-1].get('finished')}")
    if c.failed:
        print(f"COMPOSE-TEST-FAILED {case}: {c.failed} check(s) failed", flush=True)
        return 1
    print("COMPOSE-TEST-OK", flush=True)
    return 0


def print_starter(case: str) -> int:
    if case != "print-starts":
        return 0
    deadline = time.monotonic() + 600
    while time.monotonic() < deadline:
        st = _json(WORK / "blender" / "status.json") or {}
        if st.get("state") == "running":
            req = urllib.request.Request(MOCK + "/_mock/state", data=b'{"state": "printing"}',
                                         headers={"Content-Type": "application/json"})
            urllib.request.urlopen(req, timeout=10).read()
            print("print-starter: blender running, mock now printing", flush=True)
            return 0
        if st.get("state") in ("succeeded", "failed", "refused", "aborted"):
            print(f"print-starter: blender ended {st.get('state')} before it ran", flush=True)
            return 1
        time.sleep(0.5)
    print("print-starter: blender never started", flush=True)
    return 1


def main(argv) -> int:
    args = argv[1:]
    mode = args.pop(0) if args and args[0].startswith("--") else "--assert"
    case = args[0] if args else ""
    if case not in CASES:
        print(f"unknown case {case!r}; known: {', '.join(CASES)}", file=sys.stderr)
        return 2
    if mode == "--env":
        spec = CASES[case]
        print(f"MOCK_STATE={spec['mock']}")
        print(f"BLENDER_PRINT_GUARD={spec['blender_env'].get('GPU_BATCH_PRINT_GUARD', '')}")
        print(f"BLENDER_NVIDIA_VISIBLE_DEVICES={spec['blender_env'].get('NVIDIA_VISIBLE_DEVICES', '')}")
        return 0
    if mode == "--print-starter":
        return print_starter(case)
    return run_assert(case)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
